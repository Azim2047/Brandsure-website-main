/* BrandSure — service page behaviour (shared by all 4 pillar pages).
   Generated by wp/tools/build-wp-content.py from the static pages.
   Contains, unchanged: the WhatsApp dataLayer tracking, the sticky WhatsApp
   pill, and the labour-hiring requirement builder. Each block exits early when
   its markup is absent, so one file serves every service page. */
(function(){
"use strict";
/* ---- WhatsApp click tracking (dataLayer) ---- */
(function(){
  window.dataLayer = window.dataLayer || [];
  var cfg = window.BrandSureService || {};
  var b = document.body, q = new URLSearchParams(location.search);
  function pageService(){ return cfg.service || b.dataset.pageService; }
  function pageSlug(){ return cfg.slug || b.dataset.pageSlug; }
  function src(){
    var u = q.get('utm_source');
    if (u) return u + (q.get('utm_medium') ? ' / ' + q.get('utm_medium') : '');
    if (q.get('gclid')) return 'google / cpc';
    if (!document.referrer) return 'direct';
    try { return new URL(document.referrer).hostname.replace(/^www\./,''); } catch(e){ return 'referral'; }
  }
  document.addEventListener('click', function(e){
    var a = e.target.closest && e.target.closest('a[href*="wa.me"]');
    if (!a) return;
    window.dataLayer.push({
      event: 'whatsapp_click',
      page_service: pageService(),
      page_slug: pageSlug(),
      cta_position: a.dataset.cta || 'unknown',
      device: window.matchMedia('(min-width:760px)').matches ? 'desktop' : 'mobile',
      traffic_source: src(),
      campaign: q.get('utm_campaign') || null
    });
  }, true);
})();

/* ---- sticky WhatsApp pill ---- */
(function(){
  var pill=document.getElementById('wapill');if(!pill)return;
  var hero=document.querySelector('.hero'),
      ft=document.querySelector('.ft')||document.querySelector('footer'),
      inputFocused=false;
  function upd(){
    var hb=hero?hero.getBoundingClientRect().bottom:-1;
    var fr=ft?ft.getBoundingClientRect():{top:1e9};
    pill.classList.toggle('is-on',hb<0 && fr.top>=window.innerHeight*0.5 && !inputFocused);
  }
  window.addEventListener('scroll',upd,{passive:true});
  window.addEventListener('resize',upd,{passive:true});
  document.addEventListener('focusin',function(e){if(e.target.matches('input,textarea,select')){inputFocused=true;upd();}});
  document.addEventListener('focusout',function(){inputFocused=false;setTimeout(upd,150);});
  upd();
})();

/* ---- labour hiring: requirement -> WhatsApp message ---- */
(function(){
  var box = document.getElementById('requirement');
  if (!box) return;
  var send = document.getElementById('reqSend');
  var base = 'Hi BrandSure, I need help hiring furniture/sofa labour for my factory.';
  function build(){
    var roles = [].slice.call(box.querySelectorAll('input[name=role]:checked')).map(function(i){return i.value;});
    var city = (document.getElementById('req_city').value || '').trim();
    var count = (document.getElementById('req_count').value || '').trim();
    var whenEl = box.querySelector('input[name=when]:checked');
    var msg = base;
    if (roles.length) msg += '\n\nRoles needed: ' + roles.join(', ');
    if (count) msg += '\nNumber of workers: ' + count;
    if (city) msg += '\nCity / factory location: ' + city;
    if (whenEl) msg += '\nWhen needed: ' + whenEl.value;
    send.href = 'https://wa.me/918884446668?text=' + encodeURIComponent(msg);
  }
  box.addEventListener('change', build);
  box.addEventListener('input', build);
  build();
})();
})();
