<?php
/**
 * The three main-site pages: the services hub, how-it-works and pricing.
 *
 * These carry their own stylesheet inside the page body, the same way the front
 * page and About already do, so each one stays a self-contained page an owner
 * can open and edit. What they do NOT carry is a copy of the navigation or an
 * inline script: the global header supplies the first, and this file enqueues
 * the second from assets/brandsure-mainsite.js.
 *
 * @package BrandSure_Services
 */

defined( 'ABSPATH' ) || exit;

/**
 * The main-site pages, keyed by slug.
 *
 * The title is what wp-admin lists; the service name is what the WhatsApp
 * tracking reports, matching the data-page-service value the static pages used.
 *
 * @return array<string,array{title:string,service:string}>
 */
function brandsure_main_pages() {
	return array(
		'start'        => array(
			'title'   => __( 'Home', 'brandsure-services' ),
			'service' => 'Home',
		),
		'services'     => array(
			'title'   => __( 'Services', 'brandsure-services' ),
			'service' => 'Services Hub',
		),
		'how-it-works' => array(
			'title'   => __( 'How It Works', 'brandsure-services' ),
			'service' => 'How It Works',
		),
		'pricing'      => array(
			'title'   => __( 'Pricing', 'brandsure-services' ),
			'service' => 'Pricing',
		),
	);
}

/**
 * The main-site slug for the page being viewed, or '' when this is not one.
 *
 * @return string
 */
function brandsure_main_current_slug() {
	if ( ! is_page() ) {
		return '';
	}
	$post = get_queried_object();
	if ( ! $post instanceof WP_Post ) {
		return '';
	}
	$pages = brandsure_main_pages();
	return isset( $pages[ $post->post_name ] ) ? $post->post_name : '';
}

/**
 * Enqueue the behaviour these three pages need.
 *
 * Scoped to the three slugs rather than sniffed from the content, so a page
 * that still holds its own inline copy of this script can never run both and
 * report each WhatsApp click twice.
 *
 * @return void
 */
function brandsure_main_enqueue() {
	$slug = brandsure_main_current_slug();
	if ( '' === $slug ) {
		return;
	}

	$js = 'assets/brandsure-mainsite.js';
	wp_enqueue_script(
		'brandsure-mainsite',
		BRANDSURE_SERVICES_URL . $js,
		array(),
		brandsure_services_asset_version( $js ),
		true
	);

	// The static pages carried these on <body data-page-service data-page-slug>.
	// The body tag belongs to the theme here, so hand the values to the script.
	$pages = brandsure_main_pages();
	wp_add_inline_script(
		'brandsure-mainsite',
		'window.BrandSureMain=' . wp_json_encode(
			array(
				'service'  => $pages[ $slug ]['service'],
				'slug'     => $slug,
				'endpoint' => rest_url( BRANDSURE_ENQUIRY_ROUTE . '/callback' ),
			)
		) . ';',
		'before'
	);
}
add_action( 'wp_enqueue_scripts', 'brandsure_main_enqueue' );

/* -------------------------------------------------------------------------
 * Structured data — the graph the static pages carried.
 * ---------------------------------------------------------------------- */

/**
 * SEO values and JSON-LD for the main-site pages.
 *
 * Generated by wp/tools/build-main-pages.py from the static sources.
 *
 * @return array<string,array<string,mixed>>
 */
function brandsure_main_seo() {
	static $data = null;

	if ( null === $data ) {
		$file = BRANDSURE_SERVICES_DIR . 'content/main-pages.json';
		$raw  = file_exists( $file ) ? file_get_contents( $file ) : ''; // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- Local plugin asset.
		$json = '' !== $raw ? json_decode( $raw, true ) : null;
		$data = is_array( $json ) ? $json : array();
	}

	return $data;
}

/**
 * Emit the page's JSON-LD graph.
 *
 * An SEO plugin owns the title, description and canonical, but not this graph:
 * the pricing page's two Offers and its FAQ entries were written for these
 * pages and have no equivalent in a plugin's generic output.
 *
 * @return void
 */
function brandsure_main_schema() {
	$slug = brandsure_main_current_slug();
	if ( '' === $slug ) {
		return;
	}

	$seo = brandsure_main_seo();
	if ( empty( $seo[ $slug ]['jsonld'] ) || ! is_array( $seo[ $slug ]['jsonld'] ) ) {
		return;
	}

	/**
	 * Filter the JSON-LD graphs for a BrandSure main-site page.
	 *
	 * @param array  $graphs List of schema graphs.
	 * @param string $slug   Page slug.
	 */
	$graphs = apply_filters( 'brandsure_main_schema', $seo[ $slug ]['jsonld'], $slug );

	foreach ( (array) $graphs as $graph ) {
		printf(
			"<script type=\"application/ld+json\">%s</script>\n",
			wp_json_encode( $graph, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE )
		);
	}
}
add_action( 'wp_head', 'brandsure_main_schema', 2 );

/* -------------------------------------------------------------------------
 * Page body — shipped with the plugin, overridable from the editor.
 * ---------------------------------------------------------------------- */

/**
 * The generated body for one main-site page.
 *
 * content/<slug>.blocks.html is the build output of the matching static file
 * (wp/tools/build-main-pages.py). Shipping it with the plugin keeps the static
 * page the single source of truth: edit the .html, re-run the build, upload the
 * plugin. The block delimiters are stripped because this is being handed to
 * the_content already rendered.
 *
 * @param string $slug Page slug.
 * @return string Body markup, or '' when the file is missing.
 */
function brandsure_main_body( $slug ) {
	static $cache = array();

	if ( isset( $cache[ $slug ] ) ) {
		return $cache[ $slug ];
	}

	$file = BRANDSURE_SERVICES_DIR . 'content/' . $slug . '.blocks.html';
	if ( ! file_exists( $file ) ) {
		$cache[ $slug ] = '';
		return '';
	}

	$body = (string) file_get_contents( $file ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- Local plugin asset.
	$body = str_replace( array( "<!-- wp:html -->\n", "\n<!-- /wp:html -->" ), '', $body );

	$cache[ $slug ] = $body;
	return $body;
}

/**
 * Supply the body for a main-site page whose own body is empty.
 *
 * Self-deactivating: the moment the page holds its own hero the stored content
 * wins and this filter does nothing, so pasting the real markup into the editor
 * takes over cleanly and nothing has to be un-hooked.
 *
 * @param string $content Page content.
 * @return string
 */
function brandsure_main_inject( $content ) {
	if ( is_admin() || ! is_main_query() || ! in_the_loop() ) {
		return $content;
	}
	$slug = brandsure_main_current_slug();
	if ( '' === $slug ) {
		return $content;
	}
	if ( false !== strpos( $content, 'class="pagehero"' ) ) {
		return $content;
	}
	if ( '' !== trim( wp_strip_all_tags( $content ) ) ) {
		return $content;
	}

	$body = brandsure_main_body( $slug );
	if ( '' === $body ) {
		return $content;
	}

	// The public-copy corrections run at priority 8, before this, so apply them
	// to the injected body too rather than reordering a filter that is already
	// working on the pasted pages.
	if ( function_exists( 'brandsure_copy_corrections' ) ) {
		$corrections = brandsure_copy_corrections();
		$body        = str_replace(
			array_keys( $corrections ),
			array_values( $corrections ),
			$body
		);
	}

	return $body;
}
// After wpautop and wptexturize (priority 10): this body is finished markup and
// must not have paragraphs inserted into it or its characters rewritten.
add_filter( 'the_content', 'brandsure_main_inject', 11 );

/**
 * Tell an editor where the page body actually comes from.
 *
 * @param string  $post_type Current post type.
 * @param WP_Post $post      Current post.
 * @return void
 */
function brandsure_main_add_metabox( $post_type, $post ) {
	if ( 'page' !== $post_type || ! $post instanceof WP_Post ) {
		return;
	}
	$pages = brandsure_main_pages();
	if ( ! isset( $pages[ $post->post_name ] ) ) {
		return;
	}
	add_meta_box(
		'brandsure-main-source',
		__( 'BrandSure page body', 'brandsure-services' ),
		'brandsure_main_render_metabox',
		'page',
		'side',
		'high'
	);
}
add_action( 'add_meta_boxes', 'brandsure_main_add_metabox', 10, 2 );

/**
 * Render the source notice.
 *
 * @param WP_Post $post Current post.
 * @return void
 */
function brandsure_main_render_metabox( $post ) {
	$file  = 'content/' . $post->post_name . '.blocks.html';
	$empty = '' === trim( wp_strip_all_tags( $post->post_content ) );

	echo '<p>';
	if ( $empty ) {
		printf(
			/* translators: %s: plugin-relative file path. */
			esc_html__( 'This page is empty here on purpose. Its body is supplied by the BrandSure Site Infrastructure plugin from %s, which is built from the static source page.', 'brandsure-services' ),
			'<code>' . esc_html( $file ) . '</code>'
		);
		echo '</p><p>';
		esc_html_e( 'Add content here and it takes over completely — the plugin then stops supplying anything for this page.', 'brandsure-services' );
	} else {
		esc_html_e( 'This page has its own body, so the plugin is not supplying one. Empty it to go back to the version shipped with the plugin.', 'brandsure-services' );
	}
	echo '</p>';
}

/**
 * The scroll reveal, on every public page.
 *
 * Kept separate from the page scripts because it is the difference between a
 * section being visible and being invisible, and every page has .rv sections.
 *
 * @return void
 */
function brandsure_reveal_enqueue() {
	if ( is_admin() || is_embed() || is_feed() ) {
		return;
	}
	$js = 'assets/brandsure-reveal.js';
	wp_enqueue_script(
		'brandsure-reveal',
		BRANDSURE_SERVICES_URL . $js,
		array(),
		brandsure_services_asset_version( $js ),
		true
	);
}
add_action( 'wp_enqueue_scripts', 'brandsure_reveal_enqueue' );
