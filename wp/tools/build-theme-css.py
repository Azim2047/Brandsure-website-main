#!/usr/bin/env python3
"""
Build the BrandSure theme stylesheet from the static pages.

The statics carry two variants of the same design system:

  * the base sheet, identical in services.html, how-it-works.html and about.html,
    and a superset of index.html's. It holds the tokens, the resets, the shared
    components, the dark homepage hero and the secondary-page components.
  * pricing.html's sheet, which adds the pricing components (.plan, .finder,
    .fres, .keep, .calc, .compare) and redefines some shared rules using the
    --fs-*/--fw-* tokens.

The merge is a union with BASE PRECEDENCE: every base rule is kept, and from the
pricing sheet only selectors the base does not already define are added.

Base precedence is the safe direction, not an arbitrary one. Several shared
selectors differ between the two sheets -- .hero__sub is centred with a 34ch
measure in the base and left-aligned with 58ch in pricing's -- and the base
version is what /about/, /services/ and /how-it-works/ already render with on
the live site. Letting pricing's copy win would silently restyle the homepage
hero. Pricing's own page hero is already covered by the base's `.pagehero`
rules.

Run:  python3 wp/tools/build-theme-css.py
"""
import pathlib
import re
from collections import OrderedDict

ROOT = pathlib.Path(__file__).resolve().parents[2]
THEME = ROOT / "wp" / "theme" / "brandsure-theme"

BASE_SOURCES = ("services.html", "how-it-works.html", "about.html")
EXTRA_SOURCE = "pricing.html"

HEADER = """/*
Theme Name: BrandSure
Theme URI: https://brandsure.in/
Author: BrandSure Consultancy Pvt. Ltd.
Description: The BrandSure design system as a theme: one header, one footer, one stylesheet. Colours, type and components follow BSU Theme File Reference v1.0. Pages carry content only -- no page ships its own copy of the navigation or the stylesheet.
Version: 1.0.0
Requires at least: 6.0
Tested up to: 6.8
Requires PHP: 7.4
License: GPL-2.0-or-later
License URI: https://www.gnu.org/licenses/gpl-2.0.html
Text Domain: brandsure-theme
Tags: business, one-column, custom-colors, custom-menu, editor-style, translation-ready
*/

/* Generated by wp/tools/build-theme-css.py from the static pages.
   Do not edit by hand -- edit the source .html and re-run. */

"""


# Design decisions applied when the August theme baked its copies of the statics
# (update-theme.js), which exist in no source file. The header itself is styled
# by the plugin's brandsure-nav.css; what belongs here is the page-level part.
#
# Deliberately NOT included: an override of the heroes' top padding to match the
# taller 84px header. `.hero` means two different things across the site -- the
# dark full-bleed homepage hero on the main-site pages, and a white band on the
# four service pages -- so any rule specific enough to beat the page-level
# stylesheets would also add 140px of empty space above every service page. The
# 70px the heroes already reserve still clears an 84px fixed header, since they
# add another 40-110px of their own padding on top.
LIVE_REFINEMENTS = """

/* ---- carried over from the August build ---- */
html{scroll-padding-top:96px}
.ui-icon{width:1.1em;height:1.1em;display:block;fill:none;stroke:currentColor;flex:none}
"""


def first_style_block(name):
    html = (ROOT / name).read_text(encoding="utf-8")
    return re.findall(r"<style>\n(.*?)\n</style>", html, re.S)[0]


def split_rules(css):
    """Top-level rules in source order.

    An @media block is one unit, so its nested rules are never mistaken for
    top-level ones.
    """
    rules = []
    buf = ""
    depth = 0
    for ch in css:
        buf += ch
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                rules.append(buf.strip())
                buf = ""
    if buf.strip():
        rules.append(buf.strip())
    return rules


def selector_of(rule):
    """The rule's selector, or a normalised key for an @ block."""
    head = rule.split("{", 1)[0]
    return re.sub(r"\s+", " ", head).strip()


def body_of(rule):
    return rule.split("{", 1)[1].rsplit("}", 1)[0]


def merge_declarations(base_rule, extra_rule):
    """Union two declaration blocks for the same selector, base winning.

    Used for :root. The pricing sheet defines twenty tokens the base does not --
    the whole --fs-*/--fw-* type scale, plus the surface and state colours -- and
    its own components reference them, so dropping its :root would leave those
    components unstyled. No token has a conflicting value between the sheets, so
    the union is unambiguous.
    """
    have = set(re.findall(r"(--[\w-]+)\s*:", body_of(base_rule)))
    additions = [
        "{}:{}".format(name, value.strip())
        for name, value in re.findall(r"(--[\w-]+)\s*:\s*([^;]+)", body_of(extra_rule))
        if name not in have
    ]
    if not additions:
        return base_rule, []
    head, rest = base_rule.rsplit("}", 1)
    return head.rstrip().rstrip(";") + ";\n  " + ";".join(additions) + ";\n}" + rest, additions


def merge_media(base_rule, extra_rule):
    """Union two @media blocks with the same condition, base winning per selector.

    Without this the pricing page loses its responsive rules entirely -- .plans
    would stay a three-column grid on a phone.
    """
    base_inner = split_rules(body_of(base_rule))
    have = {selector_of(r) for r in base_inner}
    additions = [r for r in split_rules(body_of(extra_rule)) if selector_of(r) not in have]
    if not additions:
        return base_rule, []
    head, rest = base_rule.rsplit("}", 1)
    return head.rstrip() + "\n  " + "\n  ".join(additions) + "\n}" + rest, additions


def main():
    base_variants = {name: first_style_block(name) for name in BASE_SOURCES}
    distinct = set(base_variants.values())
    if len(distinct) != 1:
        sizes = {n: len(c) for n, c in base_variants.items()}
        raise SystemExit(
            "the base pages no longer share one stylesheet: {}".format(sizes)
        )
    base = distinct.pop()
    extra = first_style_block(EXTRA_SOURCE)

    base_rules = split_rules(base)
    extra_rules = split_rules(extra)

    # Base rules in source order, so a merge can rewrite one in place.
    order = []
    by_selector = OrderedDict()
    for rule in base_rules:
        sel = selector_of(rule)
        if sel in by_selector:
            order.append((None, rule))  # duplicate selector: keep verbatim
            continue
        by_selector[sel] = rule
        order.append((sel, None))

    added, merged_into, kept = [], [], []
    for rule in extra_rules:
        sel = selector_of(rule)

        if sel not in by_selector:
            added.append(rule)
            continue
        if rule == by_selector[sel]:
            continue

        # Same selector, different body. A declaration list or an @media block
        # is unioned; anything else keeps the base version.
        if sel.endswith(":root"):
            by_selector[sel], extras = merge_declarations(by_selector[sel], rule)
            if extras:
                merged_into.append("{} (+{} tokens)".format(sel, len(extras)))
            continue
        if sel.startswith("@media"):
            by_selector[sel], extras = merge_media(by_selector[sel], rule)
            if extras:
                merged_into.append("{} (+{} rules)".format(sel, len(extras)))
            continue

        kept.append(sel)

    body = "\n".join(
        rule if sel is None else by_selector[sel] for sel, rule in order
    )

    merged = (
        HEADER
        + body
        + "\n\n/* ---- pricing page components, from pricing.html ---- */\n"
        + "\n".join(added)
        + "\n"
        + LIVE_REFINEMENTS
    )

    THEME.mkdir(parents=True, exist_ok=True)
    (THEME / "style.css").write_text(merged, encoding="utf-8")

    print("base rules       :", len(base_rules))
    print("pricing rules    :", len(extra_rules))
    print("added from price :", len(added))
    print("unioned          :", len(merged_into))
    for note in merged_into:
        print("    ", note)
    print("kept base version:", len(kept))
    for sel in kept:
        print("    ", sel[:110])
    print("style.css        :", (THEME / "style.css").stat().st_size, "bytes")


if __name__ == "__main__":
    main()
